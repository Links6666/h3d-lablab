def _upsert_section(s: str, title: str, next_title: str, body: str,
                    uniq: str | None = None) -> str:
    """幂等替换/插入一个章节块（``body`` 自带首尾分隔线）。

    两条历史坑（2026-10-18、2026-10-23 各踩一次）都在这一个函数里收口：

    * **删除必须保留分隔线**：早先 ``s[:head] + body + s[anchor:]`` 里 head
      从标题往前找分隔线，删完不留；第二次执行时 ``rfind`` 返回 -1，整段
      被拼到文件末尾。
    * **插入必须能自愈**：锚点上方分隔线丢失时就地补一条，而不是算出一个
      -1 下标硬切片。

    同时断言章节只出现一次，防止重复追加把文件撑成两倍。``uniq`` 是用于
    计数的唯一标记 —— 修订九之下还有「修订九之二/之三…」，拿 ``title``
    直接 ``count()`` 会数出 5 次（2026-10-23 踩到）。
    """
    uniq = uniq or title
    start = s.find(title)
    if start >= 0:
        j = s.find(next_title, start)
        head = s.rfind(_SEP, 0, start)
        head = start if head < 0 else head
        if j < 0:                      # 本块在文件末尾
            s = s[:head].rstrip("\n") + "\n"
        else:
            cut = s.rfind(_SEP, start, j)
            s = s[:head] + s[j if cut < 0 else cut:]

    anchor = s.find(next_title)
    if anchor < 0:
        raise SystemExit(f"[E] 文档缺少锚点章节：{next_title}")
    sp = s.rfind(_SEP, 0, anchor)
    if sp < 0:                          # 分隔线丢了：补一条
        s = s[:anchor] + _SEP + "\n" + s[anchor:]
        anchor = s.find(next_title)
        sp = anchor - len(_SEP) - 1
    s = s[:sp] + body + s[anchor:]

    n = s.count(uniq)
    assert n == 1, f"章节「{title}」出现 {n} 次（应为 1）"
    return s


def _read(path: str) -> tuple[str, bool]:
    raw = open(path, "rb").read()
    bom = raw.startswith(b"\xef\xbb\xbf")
    return raw.decode("utf-8-sig").replace("\r\n", "\n"), bom


def _write(path: str, text: str, bom: bool) -> None:
    data = text.replace("\n", "\r\n").encode("utf-8")
    open(path, "wb").write((b"\xef\xbb\xbf" if bom else b"") + data)


def _dedupe_terms(text: str) -> str:
    """术语替换：长串在前、单字在后。

    2026-10-18 踩坑：直接 ``"造像" -> "文物"`` 会把「造像类文物」变成
    「文物类文物」；「造像类文物_xxx.pdf」这类文件名也被改错。
    规则必须长串优先，且最后兜底清掉叠词。
    """
    for a, b in (("造像类文物", "中小型文物"), ("彩塑造像", "彩塑文物"),
                 ("示例造像", "示例文物"), ("造像", "文物"),
                 ("文物类文物", "中小型文物"),
                 ("文物类（大中型）", "大型器物类（大中型）"),
                 ("文物类文物", "中小型文物"),
                 ("一尊", "一件"), ("这尊", "这件")):
        text = text.replace(a, b)
    # 「文物（米级）」要加「大型」前缀，但普通 replace 会自我叠加：
    # 「大型文物（米级）」里仍含「文物（米级）」→ 每跑一次多一个「大型」。
    # 用带前缀的整词匹配，重复执行结果不变。
    text = re.sub(r"(?:大型)*文物（米级）", "大型文物（米级）", text)
    return text


def _sha1(path: str) -> str:
    h = hashlib.sha1()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _size_str(path: str) -> str:
    try:
        return f"{os.path.getsize(path):,} B"
    except OSError:
        return "（打包后回填）"


