"""h3d.core.stages : 阶段清单的**唯一真源**。

为什么要有这个文件（2026-11-01）
--------------------------------
阶段顺序原先在仓库里有五份手写副本：``runner._reorder_ext_stages``（真正决定执行
顺序的那处）、``gui/logparse.STAGE_ORDER``、以及 ``report`` 下 csv / plot / html
三套 ``_STAGE_ORDER``。它们不一致时**不会报错**，只会让数字悄悄错位：

* 三套报表副本都缺 ``X3`` —— 而 X3 从 r19 起**默认启用**，一直在跑。
  ``html_export`` 拿 ``len(_STAGE_ORDER)`` 当完成率分母，分母因此少一个阶段，
  「件数 × 阶段数」的跨层契约对不上，状态表里也没有 X3 那一行。
* ``X1``/``X2`` 排在 ``M6`` 之后，而报表在 ``M5`` 生成 → 本轮跑完 X1/X2，报表
  读到的还是上一轮（实机：``accuracy.csv`` 的 X1 列第一次仍是 177.33）。
* 这与 r16 的「手写白名单漏键」是同构缺陷，已踩两次。

放在 ``core`` 而不是 ``runner``：core 是零依赖底座，``report`` 与 ``gui`` 都已
从它 import（``RunManifest`` / ``PipelineConfig``），不会形成 ``report → runner``
那种反向依赖。``runner.STAGE_REGISTRY`` 的顺序由本常量重排，二者必须一致
（``tests/test_report/test_stage_order.py`` 锁住）。

**改这个元组之前先想清楚**：它决定的不只是画图顺序，还有报表分母、进度权重、
断点续跑的上游阶段键。
"""

from __future__ import annotations

#: 阶段执行顺序（同时也是报表列顺序、GUI 阶段条顺序、进度分母的来源）。
#:
#: 排布理由：
#: * ``S1`` 在最前 —— 纯照片模式下它替代 M1/M2/M3 产几何；
#: * ``P1`` 紧跟 ``M4`` —— 它是对 M4 的增强，不是独立收尾；
#: * ``X3``/``X1``/``X2`` 夹在 ``P1`` 与 ``M5`` 之间 —— 三者输入分别只到
#:   M4/M3/M4，而**报表在 M5 里生成**，排在 M5 之后等于指标永远进不了报表；
#: * ``M6`` 最后 —— 它复制交付物，之后跑的任何阶段都进不了交付包。
STAGE_ORDER: tuple[str, ...] = (
    "S1", "M1", "M2", "M3", "M4", "P1",
    "X3", "X1", "X2",
    "M5", "M6",
)

__all__ = ["STAGE_ORDER"]
